#!/usr/bin/env node
/**
 * Generates src/lib/sim/scenariosMeta.ts — the client-safe list of built-in
 * scenarios (slug, title, difficulty, summary). Client components import THIS,
 * never "@/lib/sim/scenarios": that module statically imports every scenario
 * pack (questions, answers, explanations, IOCs, narratives), so importing it
 * from a "use client" file shipped every answer key inside a public
 * /_next/static chunk (QA audit, PHASE 3).
 *
 * Deliberately omitted: attack_kind (it decides the TP/FP verdict) and
 * threat_actor. Admin tooling gets those from GET /api/admin/scenarios.
 *
 * Run after adding/renaming a scenario in src/lib/sim/scenarios.ts:
 *   npx tsx scripts/generate-scenarios-meta.mjs
 * src/lib/sim/scenariosMeta.test.ts fails if this file is stale.
 */
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const ROOT = process.cwd();
const { SCENARIOS } = await import(pathToFileURL(path.join(ROOT, "src/lib/sim/scenarios.ts")).href);

const meta = SCENARIOS.map(s => ({ slug: s.slug, title: s.title, difficulty: s.difficulty, summary: s.summary }));

const out = `// AUTO-GENERATED by scripts/generate-scenarios-meta.mjs — do not hand-edit.
// Client-safe list of built-in scenarios: NO answers, explanations, IOCs,
// events, attack_kind or threat_actor. Client components import this instead of
// "@/lib/sim/scenarios" (which bundles every scenario pack and its answer key).
// Regenerate: npx tsx scripts/generate-scenarios-meta.mjs

export interface ScenarioMeta {
  slug: string;
  title: string;
  difficulty: string;
  summary: string;
}

export const SCENARIOS_META: ScenarioMeta[] = ${JSON.stringify(meta, null, 2)};
`;

writeFileSync(path.join(ROOT, "src/lib/sim/scenariosMeta.ts"), out.replace(/\n/g, "\r\n"));
console.log(`Wrote src/lib/sim/scenariosMeta.ts — ${meta.length} scenarios.`);
