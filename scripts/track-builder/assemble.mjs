#!/usr/bin/env node
/**
 * Assembles staged track content into repo data files (used by the soc-track-builder agent).
 *
 *   node scripts/track-builder/assemble.mjs <track staging folder> <trackKey> <roomsBatchNumber>
 *
 * Reads every <NN-slug>/lesson.json and room.json (in folder order) and writes
 *   src/data/<trackKey>TrackLessons.ts     export const <TRACK_KEY>_TRACK_LESSONS
 *   src/data/rooms-batch-<N>.ts            export const roomsBatch<N>
 *   docs/content-sources/<trackKey>/<NN-slug>.evidence.json  (provenance)
 * Everything goes through JSON.stringify, so no string is ever hand-escaped.
 * Registration (builtinLessons.ts, rooms.ts, recommendedTracks.ts) and the index
 * generators are separate steps: see the agent's integrate mode.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const [staging, trackKey, batch] = process.argv.slice(2);
if (!staging || !/^[a-z][a-zA-Z0-9]*$/.test(trackKey ?? "") || !/^\d+$/.test(batch ?? "")) {
  console.error("usage: assemble.mjs <track staging folder> <trackKey (camelCase)> <roomsBatchNumber>");
  process.exit(2);
}
const dirs = fs.readdirSync(staging, { withFileTypes: true })
  .filter(d => d.isDirectory() && fs.existsSync(path.join(staging, d.name, "lesson.json")))
  .map(d => d.name).sort();
if (!dirs.length) { console.error("no topic folders found"); process.exit(2); }

const read = (d, f) => JSON.parse(fs.readFileSync(path.join(staging, d, f), "utf8"));
const lessons = [], rooms = [], sourceLines = [];
const outDocs = path.join(ROOT, "docs", "content-sources", trackKey);
fs.mkdirSync(outDocs, { recursive: true });
for (const d of dirs) {
  const lesson = read(d, "lesson.json"), room = read(d, "room.json"), ev = read(d, "evidence.json");
  lessons.push(lesson); rooms.push(room);
  fs.writeFileSync(path.join(outDocs, `${d}.evidence.json`), JSON.stringify(ev, null, 2) + "\n");
  sourceLines.push(` *  ${room.id}: ${(ev.sources ?? []).length} sources, ledger docs/content-sources/${trackKey}/${d}.evidence.json`);
}

const constKey = trackKey.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
const lessonsFile = `src/data/${trackKey}TrackLessons.ts`;
fs.writeFileSync(path.join(ROOT, lessonsFile),
`// Lessons of the "${trackKey}" content track, written by the soc-track-builder agent:
// one research-backed theory lesson per topic, each paired with a Learning Room in
// rooms-batch-${batch}.ts. Same shape as CURRICULUM_EXPANSION_LESSONS; registered in
// builtinLessons.ts. Sources per lesson are in its references (not shown to learners)
// and in docs/content-sources/${trackKey}/. Generated by scripts/track-builder/assemble.mjs:
// edit the staged JSON and re-run rather than hand-editing strings here.
export const ${constKey}_TRACK_LESSONS = ${JSON.stringify(lessons, null, 2)};
`);
const roomsFile = `src/data/rooms-batch-${batch}.ts`;
fs.writeFileSync(path.join(ROOT, roomsFile),
`/**
 * Learning Rooms -- Batch ${batch}: the "${trackKey}" content track (soc-track-builder agent).
 *
 * One room per topic, each paired with a lesson in ${trackKey}TrackLessons.ts.
 * SOURCES: every technical claim and every raw log field is traced to a fetched source
 * in the per-room evidence ledger:
${sourceLines.join("\n")}
 *
 * LOG RULES: raw blocks hold observations only, fields registered per vendor in
 * scripts/log-field-registry.json, documentation-range IPs, .example domains.
 * Generated by scripts/track-builder/assemble.mjs: edit the staged JSON and re-run.
 */

export const roomsBatch${batch} = ${JSON.stringify(rooms, null, 2)};
`);
console.log(`${lessons.length} lessons -> ${lessonsFile}\n${rooms.length} rooms -> ${roomsFile}\nevidence -> docs/content-sources/${trackKey}/`);
