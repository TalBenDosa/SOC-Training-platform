#!/usr/bin/env node
/**
 * Generates src/data/libraryIndex.ts: one small card record per built-in
 * Lesson Library lesson (BUILTIN_LESSONS). The /learn page and the admin
 * syllabus list read this instead of importing BUILTIN_LESSONS, which shipped
 * all 97 full lessons (about 4.9MB of JavaScript, quiz answers included) to
 * every browser that opened /learn. A lesson's full content is fetched only
 * when it is opened, from GET /api/library/[id].
 *
 * Run after adding, removing or retitling a library lesson, or changing its
 * topic, difficulty, XP, minutes, section count or the first line of its intro:
 *   npx tsx scripts/generate-library-index.mjs
 *
 * validate-content.mjs checks this file isn't stale (same lessons, same order,
 * same fields), so a forgotten regeneration fails the content gate.
 */
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const ROOT = process.cwd();
const imp = f => import(pathToFileURL(path.join(ROOT, f)).href);

const { BUILTIN_LESSONS } = await imp("src/data/builtinLessons.ts");
const { libraryEntry } = await imp("src/lib/lessons/libraryEntry.ts");

const index = BUILTIN_LESSONS.map(libraryEntry);

const out = `// AUTO-GENERATED by scripts/generate-library-index.mjs. Do not hand-edit.
// One card record per built-in Lesson Library lesson, in BUILTIN_LESSONS order.
// Full lessons load on demand from GET /api/library/[id].
// Regenerate: npx tsx scripts/generate-library-index.mjs
// Staleness is checked by scripts/validate-content.mjs.

import type { LibraryEntry } from "@/lib/lessons/libraryEntry";

export const LIBRARY_INDEX: LibraryEntry[] = ${JSON.stringify(index, null, 2)};
`;
writeFileSync(path.join(ROOT, "src/data/libraryIndex.ts"), out);
console.log(`libraryIndex.ts: ${index.length} lessons`);
