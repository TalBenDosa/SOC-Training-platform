#!/usr/bin/env node
/**
 * Generates src/data/catalogMeta.ts: the id/title/grouping fields of every
 * built-in quiz and scenario, which is all the learning-plan catalogue
 * (src/lib/plans/catalog.ts) needs. Importing the real corpora there pulled
 * the full quiz bank (answer keys included) and every scenario builder into
 * each server function that touches plans (about 16 of them), which inflated
 * Vercel Functions Storage on every deployment.
 *
 * Run after adding, renaming or regrouping a quiz or scenario:
 *   npx tsx scripts/generate-catalog-meta.mjs
 *
 * validate-content.mjs checks this file isn't stale (same items, same order,
 * same fields), so a forgotten regeneration fails the content gate rather
 * than silently hiding an item from the plan builder.
 */
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const ROOT = process.cwd();
const imp = f => import(pathToFileURL(path.join(ROOT, f)).href);

const { ALL_QUIZZES } = await imp("src/lib/quizzes/data.ts");
const { SCENARIOS } = await imp("src/lib/sim/scenarios.ts");

const quizMeta = q => ({ slug: q.slug, title: q.title, category: q.category, difficulty: q.difficulty });
const scenarioMeta = s => ({ slug: s.slug, title: s.title, difficulty: String(s.difficulty) });

const quizzes = ALL_QUIZZES.map(quizMeta);
const scenarios = SCENARIOS.map(scenarioMeta);

const out = `// AUTO-GENERATED by scripts/generate-catalog-meta.mjs. Do not hand-edit.
// The id/title/grouping fields of every built-in quiz and scenario, in corpus
// order, for the learning-plan catalogue. No questions, answers or builders.
// Regenerate: npx tsx scripts/generate-catalog-meta.mjs
// Staleness is checked by scripts/validate-content.mjs.

export interface QuizMeta { slug: string; title: string; category: string; difficulty: string }
export interface ScenarioMeta { slug: string; title: string; difficulty: string }

export const QUIZZES_META: QuizMeta[] = ${JSON.stringify(quizzes, null, 2)};

export const SCENARIOS_META: ScenarioMeta[] = ${JSON.stringify(scenarios, null, 2)};
`;
writeFileSync(path.join(ROOT, "src/data/catalogMeta.ts"), out);
console.log(`catalogMeta.ts: ${quizzes.length} quizzes, ${scenarios.length} scenarios`);
