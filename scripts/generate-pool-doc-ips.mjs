#!/usr/bin/env node
/**
 * Generates src/lib/sim/poolDocIps.ts: every documentation address the ordinary-traffic pools use (BENIGN_EVENTS and
 * every company's COMPANY_EVENTS). The variation layer never draws one of them as an attacker's address: an address
 * one company's noise gives to a scanner or a partner is somebody in the world, with one place and one owner.
 * The pools load lazily in the browser, so the list is a small generated constant. Run after editing the pools:
 *   npx tsx scripts/generate-pool-doc-ips.mjs
 */
import { writeFileSync } from "node:fs";
const { BENIGN_EVENTS } = await import("../src/app/(app)/dashboard/benignEvents.ts");
const { COMPANY_EVENTS } = await import("../src/lib/sim/companyProfiles.ts");
const { collectDocIps } = await import("../src/lib/sim/variation.ts");
const s = new Set();
collectDocIps(BENIGN_EVENTS, s);
for (const evs of Object.values(COMPANY_EVENTS)) collectDocIps(evs, s);
const ips = [...s].sort();
writeFileSync("src/lib/sim/poolDocIps.ts", `// AUTO-GENERATED by scripts/generate-pool-doc-ips.mjs. Do not hand-edit.
/** Documentation addresses the ordinary-traffic pools use: never drawn as an attacker's address (variation.ts). */
export const POOL_DOC_IPS: readonly string[] = ${JSON.stringify(ips)};
`);
console.log(`poolDocIps.ts: ${ips.length} addresses`);
