#!/usr/bin/env node
/**
 * Generates src/data/roomsMeta.ts — a client-safe derivative of ROOMS with every
 * answer-bearing field stripped. This is the file client components (room list,
 * progress dashboard, room cards, the next-room recommender) import instead of
 * the real ROOMS, which is marked `server-only` and must never reach a browser
 * bundle.
 *
 * Run after any content change to src/data/rooms-batch-*.ts:
 *   npx tsx scripts/generate-rooms-meta.mjs
 *
 * validate-content.mjs checks this file isn't stale (room/task ids and counts
 * must match ROOMS) so a forgotten regeneration fails the content gate rather
 * than silently drifting.
 */
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const ROOT = process.cwd();
const imp = f => import(pathToFileURL(path.join(ROOT, f)).href);

const { ROOMS } = await imp("src/data/rooms.ts");

function taskMaxXp(task) {
  switch (task.type) {
    case "reading":      return 0;
    case "log_analysis": return task.questions.reduce((s, q) => s + q.xp, 0);
    default:              return task.xp;
  }
}

function taskMitreTechnique(task) {
  if (task.type === "log_analysis" || task.type === "analyst_choice") {
    return task.event?.mitre_technique;
  }
  return undefined;
}

const meta = ROOMS.map(room => ({
  id: room.id,
  title: room.title,
  description: room.description,
  difficulty: room.difficulty,
  category: room.category,
  estimatedMinutes: room.estimatedMinutes,
  xp: room.xp,
  icon: room.icon,
  prerequisites: room.prerequisites,
  tasks: room.tasks.map(t => {
    const entry = { id: t.id, type: t.type, xp: taskMaxXp(t) };
    const mitre = taskMitreTechnique(t);
    if (mitre) entry.mitreTechnique = mitre;
    return entry;
  }),
}));

const header = `// AUTO-GENERATED by scripts/generate-rooms-meta.mjs — do not hand-edit.
// A client-safe derivative of ROOMS (src/data/rooms.ts) with every
// answer-bearing field removed: no answer/answers/correct_verdict/
// correct_order/checkpoint.answer, and no embedded event raw payloads.
// This is what room-list / progress / recommender client components import —
// they must never import from "@/data/rooms" directly, which is server-only.
// Regenerate: npx tsx scripts/generate-rooms-meta.mjs
// Staleness is checked by scripts/validate-content.mjs.

export interface RoomTaskMeta {
  id: string;
  type: "reading" | "question" | "log_analysis" | "flag" | "analyst_choice" | "matching" | "ordering" | "query_fill";
  /** Max XP this task can award. 0 for reading tasks (non-gradeable). */
  xp: number;
  /** Present only for log_analysis / analyst_choice tasks whose embedded event
   *  carries a MITRE technique — not a secret, it's taught content. */
  mitreTechnique?: string;
}

export interface RoomMeta {
  id: string;
  title: string;
  description: string;
  difficulty: "beginner" | "intermediate" | "advanced";
  category: string;
  estimatedMinutes: number;
  xp: number;
  icon: string;
  prerequisites: string[];
  tasks: RoomTaskMeta[];
}

`;

const body = `export const ROOMS_META: RoomMeta[] = ${JSON.stringify(meta, null, 2)};\n`;

writeFileSync("src/data/roomsMeta.ts", header + body);
console.log(`Wrote src/data/roomsMeta.ts — ${meta.length} rooms, ${meta.reduce((s, r) => s + r.tasks.length, 0)} tasks.`);
