/**
 * Recommended Tracks: our recommended route through the whole platform, one track per level.
 *
 * A track is an ordered list of stages. Each stage teaches one area the way an analyst
 * meets it at work: read the lesson (with its slide deck and video), practise it in a
 * room, check it with a quiz, then work a scenario or a live SOC shift on it. `steps`
 * are the recommended core; `deeper` are optional extras on the same topic.
 *
 * Client-safe: steps reference content by id only. Titles, minutes, decks and videos
 * come from the generated, answer-free indexes (src/lib/tracks/resolve.ts).
 * recommendedTracks.test.ts checks every id exists, every piece of built-in content sits in
 * exactly one place, and every room's prerequisites come earlier in the route.
 */

export type TrackLevel = "beginner" | "intermediate" | "advanced";

/**
 * read     a Lesson Library lesson (LIBRARY_INDEX id), with its slide deck and video
 * lesson   a graded Learning Path lesson ("{path}--{lesson}", knowledge check, XP)
 * room     a Learning Room (ROOMS_META id)
 * quiz     a standalone quiz (QUIZZES_META slug)
 * scenario an investigation scenario (SCENARIOS_META slug)
 * shift    a live SOC Dashboard shift, done when that company is secured (COMPANY_ORDER id)
 */
export type TrackStepKind = "read" | "lesson" | "room" | "quiz" | "scenario" | "shift";

export interface TrackStep { kind: TrackStepKind; id: string }

export interface TrackStage {
  id: string;
  title: string;
  /** What the learner can do at the end of the stage, in one sentence. */
  goal: string;
  /** The concrete skills the stage builds. */
  skills: string[];
  steps: TrackStep[];
  deeper?: TrackStep[];
}

export interface RecommendedTrack {
  id: string;
  level: TrackLevel;
  /** 1, 2, 3: the order of the ladder. */
  rank: number;
  title: string;
  /** The job this track prepares for. */
  role: string;
  summary: string;
  /** Who should start here. */
  startHere: string;
  /** What the learner can do at the end of the track. */
  outcomes: string[];
  stages: TrackStage[];
}

const read = (id: string): TrackStep => ({ kind: "read", id });
const lesson = (id: string): TrackStep => ({ kind: "lesson", id });
const room = (id: string): TrackStep => ({ kind: "room", id });
const quiz = (id: string): TrackStep => ({ kind: "quiz", id });
const scenario = (id: string): TrackStep => ({ kind: "scenario", id });
const shift = (id: string): TrackStep => ({ kind: "shift", id });

