/**
 * Baseline file and the readable report for the realism gate.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { RULES, SURFACES, violationKey, type Collected, type RuleId, type Surface, type Violation } from "./types";

export const BASELINE_PATH = join(process.cwd(), "src", "lib", "logs", "realism", "realism-baseline.json");
export const REPORT_PATH = join(process.cwd(), "src", "lib", "logs", "realism", "realism-report.md");

export interface Baseline { note: string; count: number; counts: Record<string, number>; accepted: string[] }

export function readBaseline(): Baseline | null {
  if (!existsSync(BASELINE_PATH)) return null;
  return JSON.parse(readFileSync(BASELINE_PATH, "utf8")) as Baseline;
}

export function table(vs: Violation[]): Record<Surface, Record<RuleId, number>> {
  const t = Object.fromEntries(SURFACES.map(s => [s, Object.fromEntries(RULES.map(r => [r, 0]))])) as Record<Surface, Record<RuleId, number>>;
  for (const v of vs) t[v.surface][v.rule]++;
  return t;
}

export function tableText(vs: Violation[]): string {
  const t = table(vs);
  const head = `| surface | ${RULES.join(" | ")} | total |`;
  const sep = `|---|${RULES.map(() => "---:").join("|")}|---:|`;
  const rows = SURFACES.map(s => `| ${s} | ${RULES.map(r => t[s][r] || ".").join(" | ")} | ${RULES.reduce((n, r) => n + t[s][r], 0)} |`);
  const total = `| total | ${RULES.map(r => SURFACES.reduce((n, s) => n + t[s][r], 0)).join(" | ")} | ${vs.length} |`;
  return [head, sep, ...rows, total].join("\n");
}

/**
 * Write the baseline. Shrink-only: keys not in the current baseline are refused unless `allowGrow`
 * (the first generation, or an owner-approved reset).
 */
export function writeBaseline(vs: Violation[], allowGrow = false): { written: number; refused: string[] } {
  const prev = readBaseline();
  const keys = [...new Set(vs.map(violationKey))].sort();
  const refused = prev && !allowGrow ? keys.filter(k => !prev.accepted.includes(k)) : [];
  const accepted = refused.length ? keys.filter(k => prev!.accepted.includes(k)) : keys;
  const counts: Record<string, number> = {};
  for (const k of accepted) { const [s, r] = k.split("|"); counts[`${s}|${r}`] = (counts[`${s}|${r}`] ?? 0) + 1; }
  const body: Baseline = {
    note: "Reviewed realism violations (docs/LOG-REALISM-STANDARD.md) accepted so the gate blocks NEW ones while the backlog is worked down. Shrink this list; never grow it. Regenerate with `npm run realism:baseline`.",
    count: accepted.length, counts, accepted,
  };
  writeFileSync(BASELINE_PATH, JSON.stringify(body, null, 1) + "\n");
  return { written: accepted.length, refused };
}

const RULE_TITLE: Record<RuleId, string> = {
  R1: "Native fields only", R2: "Same shape for attack and benign", R3: "One identity, one id", R4: "Time is coherent",
  R5: "Addresses", R6: "Process truth", R7: "A story can be proven from its evidence", R8: "Realistic volume and severity", R9: "No answer leaks",
};

export function writeReport(c: Collected, vs: Violation[], perCell = 5): string {
  const lines: string[] = [];
  lines.push("# Log realism report", "");
  lines.push("Generated by `npm run realism:report` (src/lib/logs/realism). Rules: docs/LOG-REALISM-STANDARD.md.", "");
  lines.push("## Violations per surface and rule", "", tableText(vs), "");
  lines.push("## What was collected", "", ...c.notes.filter(n => !/collected in/.test(n)).map(n => `- ${n}`), "");
  for (const rule of RULES) {
    const rv = vs.filter(v => v.rule === rule);
    if (!rv.length) continue;
    lines.push(`## ${rule} ${RULE_TITLE[rule]} (${rv.length})`, "");
    for (const s of SURFACES) {
      const sv = rv.filter(v => v.surface === s);
      if (!sv.length) continue;
      // Most frequent details first, then a spread of examples.
      const byDetail = new Map<string, Violation[]>();
      for (const v of sv) {
        // R1 / R2: the work item is the source (file + vendor, or source/kind); others: the kind of problem.
        const d = rule === "R1" || rule === "R2"
          ? (v.rowId.includes("/") ? v.rowId : v.rowId.replace(/:[^:]*$/, ""))
          : v.detail.replace(/\b(future time in|verdict field|verdict word in|names \w+) .*/, "$1 ...").replace(/\b\d+(\.\d+){3}\b/g, "<ip>");
        (byDetail.get(d) ?? byDetail.set(d, []).get(d)!).push(v);
      }
      lines.push(`### ${s} (${sv.length})`, "");
      lines.push(...[...byDetail.entries()].sort((a, b) => b[1].length - a[1].length).slice(0, 6).map(([d, l]) => `- ${l.length} x ${d}`));
      lines.push("", "Examples:", "");
      const step = Math.max(1, Math.floor(sv.length / perCell));
      for (let i = 0, n = 0; i < sv.length && n < perCell; i += step, n++) {
        const v = sv[i];
        lines.push(`- \`${v.rowId}\`: ${v.detail}${v.example ? ` (${v.example.replace(/\|/g, "/").slice(0, 220)})` : ""}`);
      }
      lines.push("");
    }
  }
  const text = lines.join("\n") + "\n";
  writeFileSync(REPORT_PATH, text);
  return text;
}
