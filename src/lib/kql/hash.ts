/**
 * Synchronous UTF-8, base64, MD5 and SHA-256. WebCrypto is async and node:crypto does
 * not exist in the browser, and runKql has to stay synchronous, so these are local.
 */

export function utf8Encode(s: string): number[] {
  const out: number[] = [];
  for (const ch of s) {
    const c = ch.codePointAt(0) as number;
    if (c < 0x80) out.push(c);
    else if (c < 0x800) out.push(0xc0 | (c >> 6), 0x80 | (c & 63));
    else if (c < 0x10000) out.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    else out.push(0xf0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
  }
  return out;
}

/** Decodes UTF-8, replacing malformed sequences with U+FFFD. */
export function utf8Decode(bytes: number[]): string {
  const parts: string[] = [];
  let i = 0;
  while (i < bytes.length) {
    const b = bytes[i++];
    let cp = 0xfffd;
    let extra = 0;
    if (b < 0x80) cp = b;
    else if (b >= 0xc2 && b < 0xe0) { cp = b & 31; extra = 1; }
    else if (b >= 0xe0 && b < 0xf0) { cp = b & 15; extra = 2; }
    else if (b >= 0xf0 && b < 0xf5) { cp = b & 7; extra = 3; }
    let ok = true;
    for (let k = 0; k < extra; k++) {
      const n = bytes[i];
      if (n === undefined || (n & 0xc0) !== 0x80) { ok = false; break; }
      cp = (cp << 6) | (n & 63);
      i++;
    }
    parts.push(String.fromCodePoint(ok && cp <= 0x10ffff && !(cp >= 0xd800 && cp < 0xe000) ? cp : 0xfffd));
  }
  return parts.join("");
}

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

export function base64Encode(bytes: number[]): string {
  let out = "";
  for (let i = 0; i < bytes.length; i += 3) {
    const a = bytes[i];
    const b = bytes[i + 1];
    const c = bytes[i + 2];
    out += B64[a >> 2] + B64[((a & 3) << 4) | ((b ?? 0) >> 4)];
    out += b === undefined ? "=" : B64[((b & 15) << 2) | ((c ?? 0) >> 6)];
    out += c === undefined ? "=" : B64[c & 63];
  }
  return out;
}

/** Null when the input is not valid base64. */
export function base64Decode(text: string): number[] | null {
  let end = text.length;
  while (end > 0 && text[end - 1] === "=") end--;
  const s = text.slice(0, end);
  if (s.length % 4 === 1) return null;
  const out: number[] = [];
  let buf = 0;
  let bits = 0;
  for (let i = 0; i < s.length; i++) {
    const v = B64.indexOf(s[i]);
    if (v < 0) return null;
    buf = ((buf << 6) | v) & 0xffffff;
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      out.push((buf >> bits) & 255);
    }
  }
  return out;
}

function hex32(n: number): string {
  return (n >>> 0).toString(16).padStart(8, "0");
}

const MD5_S = [7, 12, 17, 22, 5, 9, 14, 20, 4, 11, 16, 23, 6, 10, 15, 21];
const MD5_K: number[] = [];
for (let i = 0; i < 64; i++) MD5_K[i] = Math.floor(Math.abs(Math.sin(i + 1)) * 2 ** 32);

export function md5Hex(input: number[]): string {
  const bytes = input.slice();
  const bitLen = input.length * 8;
  bytes.push(0x80);
  while (bytes.length % 64 !== 56) bytes.push(0);
  for (let i = 0; i < 8; i++) bytes.push(i < 4 ? (bitLen >>> (8 * i)) & 255 : i < 8 ? Math.floor(bitLen / 2 ** (8 * i)) & 255 : 0);
  let a0 = 0x67452301;
  let b0 = 0xefcdab89;
  let c0 = 0x98badcfe;
  let d0 = 0x10325476;
  for (let off = 0; off < bytes.length; off += 64) {
    const m: number[] = [];
    for (let i = 0; i < 16; i++) {
      const j = off + i * 4;
      m[i] = (bytes[j] | (bytes[j + 1] << 8) | (bytes[j + 2] << 16) | (bytes[j + 3] << 24)) >>> 0;
    }
    let [a, b, c, d] = [a0, b0, c0, d0];
    for (let i = 0; i < 64; i++) {
      let f: number;
      let g: number;
      if (i < 16) { f = (b & c) | (~b & d); g = i; }
      else if (i < 32) { f = (d & b) | (~d & c); g = (5 * i + 1) % 16; }
      else if (i < 48) { f = b ^ c ^ d; g = (3 * i + 5) % 16; }
      else { f = c ^ (b | ~d); g = (7 * i) % 16; }
      const tmp = d;
      d = c;
      c = b;
      const sum = (a + f + MD5_K[i] + m[g]) >>> 0;
      const s = MD5_S[Math.floor(i / 16) * 4 + (i % 4)];
      b = (b + (((sum << s) | (sum >>> (32 - s))) >>> 0)) >>> 0;
      a = tmp;
    }
    a0 = (a0 + a) >>> 0;
    b0 = (b0 + b) >>> 0;
    c0 = (c0 + c) >>> 0;
    d0 = (d0 + d) >>> 0;
  }
  const le = (n: number) => hex32(((n & 255) << 24) | ((n & 0xff00) << 8) | ((n >>> 8) & 0xff00) | (n >>> 24));
  return le(a0) + le(b0) + le(c0) + le(d0);
}

